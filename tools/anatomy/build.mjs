// Bundles the anatomy kit, the motor geometry (figure.mjs) and the runtime into js/motor-anatomy.js,
// a classic script, so index.html still works when opened straight from disk.
// Run: node tools/anatomy/build.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure } from "./figure.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const source = (file) => readFileSync(join(HERE, file), "utf8");
const strip = (text) => text.replace(/^import .*$/gm, "").replace(/^export /gm, "");
const namesOf = (text) => [...text.matchAll(/^export (?:async )?(?:function\*?|const|let|class) ([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
const module = (text, prelude = "") => `(() => { ${prelude}\n${strip(text)}\nreturn { ${namesOf(text).join(", ")} }; })()`;

// Sanity check and timing in Node: every pose must build.
const started = performance.now();
for (const t of [0, 0.25, 0.5, 0.75, 1]) for (const [azimuth, elevation] of [[15, 12], [50, 30], [80, 58]]) buildFigure({ azimuth, elevation, t });
const per = (performance.now() - started) / 15;

const iso = source("kit/iso-kit.mjs"), lathe = source("kit/lathe.mjs"), tube = source("kit/tube.mjs");
const out = `/* Generated by tools/anatomy/build.mjs from figure.mjs, runtime.js and kit/ — do not edit by hand. */
(() => {
const k = ${module(iso)};
const G = ${module(lathe, "const { cameraOf, iso, pathOf } = k;")};
const T = ${module(tube, "const { iso, pathOf } = k;")};
const { buildFigure, FIGURE } = ${module(source("figure.mjs"))};
${source("runtime.js")}
})();
`;
writeFileSync(join(ROOT, "js", "motor-anatomy.js"), out);
writeFileSync(join(ROOT, "css", "iso.css"), source("kit/iso.css"));
console.log(`wrote js/motor-anatomy.js ${(out.length / 1024).toFixed(0)} KB · buildFigure ${per.toFixed(0)} ms per pose in Node`);
